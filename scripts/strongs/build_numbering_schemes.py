"""
build_numbering_schemes.py — which verse numbering each Bible edition follows, for the Strong's window.

The window shows a Hebrew verse and, under it, the SAME verse in the reader's Bible. The Hebrew
text and the KJV number some verses differently (Gen 32:1 is KJV 31:55), so the verse has to be
mapped — and only for editions whose numbering is known. This writes
app/src/main/resources/versification/schemes.properties, one line per edition:

    bible-kjv-1611=kjv        English numbering: map a Hebrew verse through wlc-kjv-versemap.xml
    bible-lut1912-1912=hebrew   the Hebrew numbering itself: use the Hebrew reference unchanged

An edition not listed has unknown numbering and gets NO translation line (never a guess).

Rules, from docs/versification-ledger.tsv (scripts/bibles/classify_versification.py):
  * a reviewed `scheme` of kjv or hebrew wins;
  * guess `kjv` or `kjv-like` (no numbering shift detected) -> kjv;
  * guess `hebrew-chapters+psalm-titles` (both Hebrew signals) -> hebrew;
  * everything else (Psalm titles only, Greek/Latin Psalter, unclassified) -> not listed;
  * OVERRIDES below: editions confirmed by hand.
This is a stopgap for the verse map (docs/cross-references-design.md milestone 5): when that lands,
it replaces this file.

Usage:  python3 scripts/strongs/build_numbering_schemes.py
"""
import csv, os

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
LEDGER = os.path.join(REPO, "docs", "versification-ledger.tsv")
OUT = os.path.join(REPO, "app", "src", "main", "resources", "versification", "schemes.properties")

# Confirmed by hand, not by verse counts. The NIV follows English numbering; the ledger cannot
# say so because its many omitted verses defeat the "no differing chapters" test. The KJV is the
# ledger's reference, so it is not in the ledger; the WLC IS the Hebrew numbering.
OVERRIDES = {"bible-kjv-1611": "kjv", "bible-niv-2011": "kjv", "bible-he-wlc": "hebrew"}


def scheme_of(row):
    if row["reviewed"] == "yes" and row["scheme"] in ("kjv", "hebrew"):
        return row["scheme"]
    g = row["guess"]
    if g in ("kjv", "kjv-like"):
        return "kjv"
    if g == "hebrew-chapters+psalm-titles":
        return "hebrew"
    return None


def main():
    with open(LEDGER, encoding="utf-8") as f:
        rows = list(csv.DictReader((l for l in f if not l.startswith("#")), delimiter="\t"))
    out = {r["edition"]: s for r in rows if (s := scheme_of(r))}
    out.update(OVERRIDES)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("# Verse numbering per Bible edition (generated by scripts/strongs/build_numbering_schemes.py).\n"
                "# kjv = English numbering (map a Hebrew verse through wlc-kjv-versemap.xml); hebrew = the Hebrew\n"
                "# numbering itself. An edition not listed has unknown numbering and gets no translation line.\n")
        for ed in sorted(out):
            f.write("%s=%s\n" % (ed, out[ed]))
    n = {}
    for s in out.values():
        n[s] = n.get(s, 0) + 1
    print("wrote %s: %d editions %s" % (OUT, len(out), n))


if __name__ == "__main__":
    main()
