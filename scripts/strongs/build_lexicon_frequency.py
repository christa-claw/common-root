"""
build_lexicon_frequency.py — how often each Strong's number occurs in the Hebrew Bible.

The lexicon translation job (docs/lexicon-translation-job.md) works through the entries most
likely to be hovered first, so it needs an order. This writes docs/lexicon-frequency-hebrew.tsv:
`H####<TAB>count`, most frequent first (ties by number), then the numbers that never occur, by
number. Counted from the word layer (out/strongs/words-oshb.xml, one count per tagged word).

The table is committed so the job and its check script never need the OSHB download.

Usage:
    python3 scripts/strongs/build_lexicon_frequency.py [--words out/strongs/words-oshb.xml]
"""
import argparse, collections, os, re, sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
NS = "{http://religioustext.org/schema/words/1.0}"


def count_words(path):
    counts = collections.Counter()
    for _, el in ET.iterparse(path, events=("end",)):
        if el.tag == NS + "w":
            s = el.get("strongs")
            if s:
                counts[s] += 1
            el.clear()
    return counts


def english_ids(props_path):
    ids = set()
    for line in open(props_path, encoding="utf-8"):
        m = re.match(r"(H\d+)\.gloss=", line)
        if m:
            ids.add(m.group(1))
    return ids


def ordered(counts, all_ids):
    """Most frequent first (ties by number), then the unused numbers by number."""
    key = lambda s: int(s[1:])
    used = sorted((s for s in all_ids if counts.get(s)), key=lambda s: (-counts[s], key(s)))
    unused = sorted((s for s in all_ids if not counts.get(s)), key=key)
    return [(s, counts.get(s, 0)) for s in used + unused]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--words", default=os.path.join(REPO, "out", "strongs", "words-oshb.xml"))
    ap.add_argument("--props", default=os.path.join(REPO, "app", "src", "main", "resources", "i18n", "lexicon", "hebrew.properties"))
    ap.add_argument("--out", default=os.path.join(REPO, "docs", "lexicon-frequency-hebrew.tsv"))
    a = ap.parse_args()
    if not os.path.exists(a.words):
        sys.exit("No %s — run scripts/strongs/build_words_oshb.py first." % a.words)
    rows = ordered(count_words(a.words), english_ids(a.props))
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("# Occurrences of each Strong's Hebrew number in the OSHB word layer, most frequent first.\n"
                "# Order of work for the lexicon translation job. Generated by scripts/strongs/build_lexicon_frequency.py.\n")
        for sid, n in rows:
            f.write("%s\t%d\n" % (sid, n))
    used = sum(1 for _, n in rows if n)
    print("wrote %s: %d numbers (%d occur, %d never)" % (a.out, len(rows), used, len(rows) - used))
    print("top:", ", ".join("%s=%d" % r for r in rows[:5]))


if __name__ == "__main__":
    main()
