"""
build_lexicon_greek.py — the English base text for the Greek Strong's tooltip, as a .properties file.

Reads STEPBible's TBESG (Translators Brief lexicon of Extended Strongs for Greek, built on Abbott-Smith)
and writes app/src/main/resources/i18n/lexicon/greek.properties, in the same shape as hebrew.properties:

    G2424.lemma=Ἰησοῦς           language-neutral
    G2424.xlit=Iēsous            language-neutral
    G2424.gloss=Jesus            translated per locale (greek_fi.properties, ...)
    G2424.def=Jesus, ...         translated per locale

One entry per plain Strong's number (G1 - G5624): the first TBESG row for the number. Extended senses
(G2424G, G2424H ...) share the entry. Abbott-Smith's markup is reduced to plain text; scripture
references are kept as written; the definition is cut at about 450 characters (a brief lexicon).
Output is sorted by number, so a regenerated file diffs cleanly.

Usage:
    python3 scripts/strongs/build_lexicon_greek.py [--file TBESG.txt] [--out FILE]
"""
import argparse, glob, html, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
MAX_DEF = 450

HEADER = """# Greek lexicon text for the Strong's tooltip — English base (docs/strongs-design.md).
#
# Source: STEPBible's TBESG, the Translators Brief lexicon of Extended Strongs for Greek
# (https://github.com/STEPBible/STEPBible-Data), data created by www.STEPBible.org based on work at
# Tyndale House Cambridge, CC BY 4.0. Its definitions are Abbott-Smith's Manual Greek Lexicon of the
# New Testament (public domain), edited by STEPBible.
# Changes made: one entry per Strong's number (the first row for it); markup reduced to plain text;
# definitions cut to about 450 characters.
#
# .lemma and .xlit are language-neutral. .gloss and .def are translated per locale in
# greek_<lang>.properties (machine-translated, unreviewed); a missing key falls back to this file.
# Generated by scripts/strongs/build_lexicon_greek.py — edit the script, not this file.
"""


def default_file():
    root = os.path.abspath(os.path.join(HERE, "..", ".."))
    for base in (root, os.path.join(os.path.dirname(root), "religious-texts")):   # a worktree finds the main checkout's downloads
        hits = glob.glob(os.path.join(base, "sources", "stepbible", "TBESG*.txt"))
        if hits:
            return hits[0]
    sys.exit("TBESG download not found under sources/stepbible (see sources/stepbible/SOURCE.md).")


def esc(value):
    """.properties value escaping: backslash, line breaks, and leading blanks (UTF-8 is written as is)."""
    value = value.replace("\\", "\\\\").replace("\r", " ").replace("\n", " ").strip()
    return re.sub(r"^ ", r"\\ ", value)


def plain(markup):
    """Abbott-Smith's HTML-ish markup as one line of plain text."""
    t = re.sub(r"<BR\s*/?>", " ", markup, flags=re.I)
    t = re.sub(r"<[^>]+>", "", t)
    t = html.unescape(t).replace("†", "").replace("*", "")
    t = re.sub(r"\(AS\)\s*$", "", t.strip())
    t = re.sub(r"\s+", " ", t).strip()
    t = re.sub(r"__(\d)\.", r"\1.", t)
    return t


def clip(text, limit=MAX_DEF):
    if len(text) <= limit:
        return text
    cut = text[:limit].rsplit(" ", 1)[0].rstrip(" ,;:")
    return cut + " …"


def entries(path):
    """Yield (id, lemma, xlit, gloss, definition) for the first row of each plain number, in order."""
    seen = set()
    rows = []
    for line in open(path, encoding="utf-8-sig"):
        m = re.match(r"^G(\d{4})\t", line)
        if not m:
            continue
        num = int(m.group(1))
        if num > 5624 or num in seen:
            continue
        cols = line.rstrip("\n").split("\t")
        if len(cols) < 8:
            continue
        seen.add(num)
        rows.append((num, cols))
    for num, cols in sorted(rows):
        yield "G%d" % num, cols[3].strip(), cols[4].strip(), cols[6].strip(), clip(plain(cols[7]))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--file", default=None)
    ap.add_argument("--out", default=os.path.join(HERE, "..", "..", "app", "src", "main", "resources",
                                                 "i18n", "lexicon", "greek.properties"))
    a = ap.parse_args()
    src = a.file or default_file()
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    n = skipped = 0
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER + "\n")
        for sid, lemma, xlit, gloss, definition in entries(src):
            if not (gloss or definition):
                skipped += 1
                continue
            f.write("%s.lemma=%s\n%s.xlit=%s\n%s.gloss=%s\n%s.def=%s\n" % (
                sid, esc(lemma), sid, esc(xlit), sid, esc(gloss), sid, esc(definition)))
            n += 1
    print("wrote %s: %d entries (%d without text skipped), %d bytes" % (
        os.path.abspath(a.out), n, skipped, os.path.getsize(a.out)))


if __name__ == "__main__":
    main()
