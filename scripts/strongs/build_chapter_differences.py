"""
build_chapter_differences.py — which chapters of each Bible edition have a different verse count
from the KJV, for the Strong's window's translation line.

An edition can follow English numbering overall yet split or merge verses inside a few chapters
(the RVR09 differs in 25 chapters). Mapping a Hebrew verse into such a chapter could land one verse
off. So VerseNumbering shows NO translation for a verse in a chapter listed here, and a translation
everywhere else: the cost is a missing line in a few chapters, never a wrong one.

Writes app/src/main/resources/versification/chapter-differences.properties:

    bible-rvr09-1909=GEN.12,GEN.13,...        (USFM book code . chapter)

Read-only against local BaseX (the same counts classify_versification.py uses). The reference is the KJV
(bible-kjv-1611); only chapters the edition HAS but counts differently, or lacks, are listed — a book
the edition does not carry at all (an NT-only edition) is simply absent, so is not listed.

Usage:  python3 scripts/strongs/build_chapter_differences.py
"""
import importlib, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(REPO, "scripts", "bibles"))
classify = importlib.import_module("classify_versification")

OUT = os.path.join(REPO, "app", "src", "main", "resources", "versification", "chapter-differences.properties")
REFERENCE = "bible-kjv-1611"


def differences(edition_counts, reference_counts):
    """Sorted 'BOOK.chapter' for chapters of books the edition carries whose count differs or is missing."""
    shared = {b for b, _ in edition_counts}
    return sorted(("%s.%d" % (b, c) for (b, c), n in reference_counts.items()
                   if b in shared and edition_counts.get((b, c)) != n),
                  key=lambda s: (classify.CANON.index(s.split(".")[0]), int(s.split(".")[1])))


def main():
    counts = classify.all_counts()
    ref = counts.pop(REFERENCE, None)
    if not ref:
        sys.exit("No chapters found for %s — is BaseX running and the edition imported?" % REFERENCE)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("# Chapters whose verse count differs from the KJV, per Bible edition (USFM book.chapter).\n"
                "# Generated by scripts/strongs/build_chapter_differences.py. VerseNumbering shows no translation\n"
                "# for a verse in a listed chapter (a split or merged verse could put it one off).\n")
        total = 0
        for ed in sorted(counts):
            d = differences(counts[ed], ref)
            if d:
                f.write("%s=%s\n" % (ed, ",".join(d)))
                total += len(d)
    print("wrote %s: %d editions, %d chapters listed" % (OUT, sum(1 for e in counts if differences(counts[e], ref)), total))


if __name__ == "__main__":
    main()
