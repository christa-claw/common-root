"""
build_lexicon_properties.py — the English base text for the Strong's tooltip, as a .properties file.

Milestone 4 of docs/strongs-design.md. Reads the Open Scriptures Hebrew Lexicon (Strong's entries
joined to the lexical index) and writes app/src/main/resources/i18n/lexicon/hebrew.properties:

    H430.lemma=אֱלֹהִים            language-neutral (never translated)
    H430.xlit=ʾĕlōhîm              language-neutral
    H430.gloss=gods; God; magistrates       translated per locale (hebrew_fi.properties, ...)
    H430.def=gods in the ordinary sense; but specifically ...   translated per locale

One entry per Strong's number (the sense letter does not change the entry). Strong's "usage" line
is NOT written: it lists the KJV's English renderings, which is data about one translation.
Locale files carry only .gloss and .def; a missing key falls back to this English file.

The properties live in the repository (public), so each file starts with the CC BY credit.
Output is sorted by number, so a regenerated file diffs cleanly.

Usage:
    python3 scripts/strongs/build_lexicon_properties.py [--lexicon DIR] [--out FILE]
"""
import argparse, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import oshb_lemma as L
import preview_verse as P

HEADER = """# Hebrew lexicon text for the Strong's tooltip — English base (docs/strongs-design.md).
#
# Source: the Open Scriptures Hebrew Lexicon (https://github.com/openscriptures/HebrewLexicon),
# credited to the Open Scriptures Hebrew Bible Project, CC BY 4.0. The text of Brown-Driver-Briggs
# and of Strong's Hebrew dictionary remains in the public domain.
# Changes made: one entry per Strong's number; glosses taken from the definition's key words;
# Strong's "usage" line (the KJV's English renderings) omitted.
#
# .lemma and .xlit are language-neutral. .gloss and .def are translated per locale in
# hebrew_<lang>.properties (machine-translated, unreviewed); a missing key falls back to this file.
# Generated by scripts/strongs/build_lexicon_properties.py — edit the script, not this file.
"""


def esc(value):
    """.properties value escaping: backslash, line breaks, and leading blanks (UTF-8 is written as is)."""
    value = value.replace("\\", "\\\\").replace("\r", " ").replace("\n", " ").strip()
    return re.sub(r"^ ", r"\\ ", value)


def entries(strong, lex, aug):
    """Yield (number, lemma, xlit, gloss, definition) for every Strong's Hebrew number."""
    for sid in sorted(strong, key=lambda k: int(k[1:])):
        st = strong[sid]
        li = lex.get(aug.resolve(sid[1:]) or "", {})
        gloss = "; ".join(st["glosses"][:3]) or li.get("def", "")
        # Strong's gives some entries only a "corresponding to H1"-style source line and no meaning.
        # (its references are bare numbers in the source: write them as Strong's ids, "corresponding to H1")
        definition = st["meaning"] or re.sub(r"\b(\d+)\b", r"H\1", st["source"].rstrip(";: ").strip())
        yield (sid, li.get("lemma") or st["lemma"], li.get("xlit") or st["xlit"], gloss, definition)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--lexicon", default=os.path.dirname(L._default("sources", "hebrew-lexicon", "src", "AugIndex.xml")))
    ap.add_argument("--out", default=os.path.join(HERE, "..", "..", "app", "src", "main", "resources",
                                                 "i18n", "lexicon", "hebrew.properties"))
    a = ap.parse_args()
    aug = L.AugIndex.load(os.path.join(a.lexicon, "AugIndex.xml"))
    strong = P.load_strong(os.path.join(a.lexicon, "HebrewStrong.xml"))
    lex = P.load_lexical_index(os.path.join(a.lexicon, "LexicalIndex.xml"))

    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    n = skipped = 0
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER + "\n")
        for sid, lemma, xlit, gloss, definition in entries(strong, lex, aug):
            if not (gloss or definition):
                skipped += 1
                continue
            f.write("%s.lemma=%s\n%s.xlit=%s\n%s.gloss=%s\n%s.def=%s\n" % (
                sid, esc(lemma), sid, esc(xlit), sid, esc(gloss), sid, esc(definition)))
            n += 1
    print("wrote %s: %d entries (%d without text skipped), %d bytes" % (
        os.path.abspath(a.out), n, skipped, os.path.getsize(a.out)))


if __name__ == "__main__":
    main()
